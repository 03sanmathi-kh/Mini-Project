CREATE TABLE officer_routing (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 officer_id BIGINT NOT NULL REFERENCES app_users(id),
 permit_type VARCHAR(80) NOT NULL, zone VARCHAR(80) NOT NULL,
 assignment_type VARCHAR(30) NOT NULL,
 sla_hours INTEGER CHECK(sla_hours > 0 AND sla_hours <= 8760),
 UNIQUE(officer_id,permit_type,zone,assignment_type)
);
CREATE TABLE unassigned_work (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 assignment_type VARCHAR(30) NOT NULL, reason VARCHAR(500) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, resolved BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(application_id,assignment_type)
);
CREATE TABLE notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id BIGINT NOT NULL REFERENCES app_users(id),
 application_id BIGINT REFERENCES permit_applications(id),
 event VARCHAR(100) NOT NULL, message VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, read_at TIMESTAMP WITH TIME ZONE,
 sms_status VARCHAR(40) NOT NULL
);
CREATE INDEX notification_recipient ON notifications(recipient_id,created_at);
CREATE TABLE audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES app_users(id),
 action VARCHAR(100) NOT NULL, event_date DATE NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
 entity_type VARCHAR(80) NOT NULL, entity_id BIGINT NOT NULL,
 details VARCHAR(2000) NOT NULL
);
CREATE INDEX audit_entity ON audit_log(entity_type,entity_id,occurred_at);
CREATE TABLE document_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 document_name VARCHAR(150) NOT NULL, version_no INTEGER NOT NULL CHECK(version_no > 0),
 content_type VARCHAR(100) NOT NULL, content_hash VARCHAR(64) NOT NULL,
 content_size BIGINT NOT NULL CHECK(content_size > 0 AND content_size <= 5242880),
 content_base64 TEXT NOT NULL,
 uploaded_by BIGINT NOT NULL REFERENCES app_users(id), uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(application_id,document_name,version_no)
);

