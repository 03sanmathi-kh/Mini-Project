ALTER TABLE app_users ADD COLUMN personal_contact_email VARCHAR(254);
ALTER TABLE security_events ALTER COLUMN actor_id DROP NOT NULL;
ALTER TABLE app_users ADD CONSTRAINT ck_app_users_personal_email_normalized
 CHECK (personal_contact_email IS NULL OR personal_contact_email = LOWER(TRIM(personal_contact_email)));
CREATE INDEX idx_app_users_personal_email ON app_users(personal_contact_email);

CREATE SEQUENCE support_ticket_numbers START WITH 1 INCREMENT BY 1;

CREATE TABLE support_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_number VARCHAR(30) NOT NULL UNIQUE,
 requester_name VARCHAR(100) NOT NULL,
 personal_contact_email VARCHAR(254) NOT NULL,
 permitworks_email VARCHAR(254),
 contact_phone VARCHAR(30),
 category VARCHAR(40) NOT NULL,
 subject VARCHAR(160) NOT NULL,
 description VARCHAR(4000) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 admin_notes VARCHAR(4000),
 user_visible_response VARCHAR(4000),
 handled_by_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,
 request_ip_hash VARCHAR(64) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 resolved_at TIMESTAMP WITH TIME ZONE,
 CONSTRAINT ck_support_personal_email_normalized CHECK (personal_contact_email = LOWER(TRIM(personal_contact_email))),
 CONSTRAINT ck_support_permitworks_email CHECK (permitworks_email IS NULL OR (permitworks_email = LOWER(TRIM(permitworks_email)) AND permitworks_email LIKE '%@permitworks.com')),
 CONSTRAINT ck_support_status CHECK (status IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED'))
);

CREATE INDEX idx_support_personal_email ON support_requests(personal_contact_email);
CREATE INDEX idx_support_permitworks_email ON support_requests(permitworks_email);
CREATE INDEX idx_support_status ON support_requests(status);
CREATE INDEX idx_support_category ON support_requests(category);
CREATE INDEX idx_support_created_at ON support_requests(created_at DESC);
CREATE INDEX idx_support_rate_limit ON support_requests(request_ip_hash,created_at DESC);
