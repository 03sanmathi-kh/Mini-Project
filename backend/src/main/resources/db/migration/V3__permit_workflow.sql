CREATE TABLE permit_applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 permit_number VARCHAR(30) UNIQUE,
 applicant_id BIGINT NOT NULL REFERENCES app_users(id),
 project_title VARCHAR(150) NOT NULL,
 permit_type VARCHAR(80) NOT NULL,
 property_address VARCHAR(300) NOT NULL,
 construction_description VARCHAR(2000) NOT NULL,
 property_owner_name VARCHAR(150) NOT NULL,
 contractor_architect_name VARCHAR(150) NOT NULL,
 estimated_project_cost NUMERIC(14,2) NOT NULL CHECK (estimated_project_cost >= 0),
 proposed_start_date DATE NOT NULL,
 supporting_documents VARCHAR(2000) NOT NULL,
 status VARCHAR(40) NOT NULL,
 review_round INTEGER NOT NULL DEFAULT 1 CHECK (review_round > 0),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_permit_owner ON permit_applications(applicant_id);
CREATE INDEX idx_permit_status ON permit_applications(status);
CREATE TABLE application_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES permit_applications(id), review_round INTEGER NOT NULL,
 project_title VARCHAR(150) NOT NULL, permit_type VARCHAR(80) NOT NULL, property_address VARCHAR(300) NOT NULL,
 construction_description VARCHAR(2000) NOT NULL, property_owner_name VARCHAR(150) NOT NULL,
 contractor_architect_name VARCHAR(150) NOT NULL, estimated_project_cost NUMERIC(14,2) NOT NULL,
 proposed_start_date DATE NOT NULL, supporting_documents VARCHAR(2000) NOT NULL,
 submitted_at TIMESTAMP WITH TIME ZONE NOT NULL, UNIQUE(application_id, review_round)
);
CREATE TABLE application_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 assignment_type VARCHAR(30) NOT NULL, assignee_id BIGINT NOT NULL REFERENCES app_users(id),
 assigned_by BIGINT NOT NULL REFERENCES app_users(id), assigned_at TIMESTAMP WITH TIME ZONE NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_assignment_lookup ON application_assignments(application_id, assignment_type, active);
CREATE INDEX idx_assignment_assignee ON application_assignments(assignee_id, active);
CREATE TABLE application_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 review_type VARCHAR(20) NOT NULL, reviewer_id BIGINT NOT NULL REFERENCES app_users(id), recommendation VARCHAR(30) NOT NULL,
 remarks VARCHAR(2000), review_date TIMESTAMP WITH TIME ZONE NOT NULL, review_round INTEGER NOT NULL
);
CREATE INDEX idx_review_application ON application_reviews(application_id, review_round);
CREATE TABLE correction_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 requested_by BIGINT NOT NULL REFERENCES app_users(id), requesting_role VARCHAR(40) NOT NULL, remarks VARCHAR(2000) NOT NULL,
 requested_at TIMESTAMP WITH TIME ZONE NOT NULL, resolved BOOLEAN NOT NULL DEFAULT FALSE, applicant_response VARCHAR(2000),
 resubmitted_at TIMESTAMP WITH TIME ZONE, review_round INTEGER NOT NULL
);
CREATE INDEX idx_correction_application ON correction_requests(application_id, resolved);
CREATE TABLE payment_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id BIGINT NOT NULL REFERENCES permit_applications(id) UNIQUE,
 fee_amount NUMERIC(14,2) NOT NULL CHECK (fee_amount >= 0), payment_status VARCHAR(20) NOT NULL,
 payment_reference VARCHAR(100), recorded_by BIGINT NOT NULL REFERENCES app_users(id), recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE inspections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 inspector_id BIGINT NOT NULL REFERENCES app_users(id), inspection_type VARCHAR(100) NOT NULL, scheduled_date DATE NOT NULL,
 conducted_date DATE, observations VARCHAR(2000), result VARCHAR(20) NOT NULL, final_inspection BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_inspection_assignee ON inspections(inspector_id, result);
CREATE INDEX idx_inspection_application ON inspections(application_id);
CREATE TABLE workflow_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, application_id BIGINT NOT NULL REFERENCES permit_applications(id),
 previous_status VARCHAR(40), new_status VARCHAR(40) NOT NULL, action VARCHAR(100) NOT NULL, remarks VARCHAR(2000),
 actor_id BIGINT NOT NULL REFERENCES app_users(id), actor_name VARCHAR(100) NOT NULL, actor_email VARCHAR(254) NOT NULL,
 actor_role VARCHAR(40) NOT NULL, occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_history_application ON workflow_history(application_id, occurred_at);
