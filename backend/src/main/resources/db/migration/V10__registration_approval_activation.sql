CREATE TABLE registration_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 personal_email VARCHAR(254) NOT NULL,
 active_email VARCHAR(254) UNIQUE,
 phone VARCHAR(20) NOT NULL,
 requested_role VARCHAR(40) NOT NULL,
 approved_role VARCHAR(40),
 description VARCHAR(2000),
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
 tracking_hash VARCHAR(64) NOT NULL UNIQUE,
 activation_hash VARCHAR(64),
 submitted_at TIMESTAMP WITH TIME ZONE NOT NULL,
 reviewed_at TIMESTAMP WITH TIME ZONE,
 reviewed_by BIGINT REFERENCES app_users(id),
 rejection_reason VARCHAR(500),
 user_id BIGINT UNIQUE REFERENCES app_users(id),
 activation_expires_at TIMESTAMP WITH TIME ZONE,
 activated_at TIMESTAMP WITH TIME ZONE,
 CONSTRAINT registration_email_normalized CHECK (personal_email=LOWER(TRIM(personal_email))),
 CONSTRAINT registration_active_identity CHECK (active_email IS NULL OR active_email=personal_email),
 CONSTRAINT registration_tracking_digest CHECK (CHAR_LENGTH(tracking_hash)=64),
 CONSTRAINT registration_activation_digest CHECK (activation_hash IS NULL OR CHAR_LENGTH(activation_hash)=64),
 CONSTRAINT registration_requested_role CHECK (requested_role IN ('ADMIN','APPLICANT','DEPARTMENT_OFFICER','PERMIT_REVIEWER','ZONING_OFFICER','SENIOR_DEPARTMENT_OFFICER','FINANCE_OFFICER','BUILDING_INSPECTOR')),
 CONSTRAINT registration_approved_role CHECK (approved_role IS NULL OR approved_role IN ('ADMIN','APPLICANT','DEPARTMENT_OFFICER','PERMIT_REVIEWER','ZONING_OFFICER','SENIOR_DEPARTMENT_OFFICER','FINANCE_OFFICER','BUILDING_INSPECTOR')),
 CONSTRAINT registration_state CHECK (
  (status='PENDING' AND active_email IS NOT NULL AND user_id IS NULL AND approved_role IS NULL AND reviewed_at IS NULL AND reviewed_by IS NULL AND activation_hash IS NOT NULL AND activated_at IS NULL AND activation_expires_at IS NULL AND rejection_reason IS NULL)
  OR (status='APPROVED' AND active_email IS NOT NULL AND user_id IS NOT NULL AND approved_role IS NOT NULL AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL AND activation_hash IS NOT NULL AND activation_expires_at IS NOT NULL AND activated_at IS NULL AND rejection_reason IS NULL)
  OR (status='REJECTED' AND active_email IS NULL AND user_id IS NULL AND approved_role IS NULL AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL AND activation_hash IS NULL AND activation_expires_at IS NULL AND activated_at IS NULL AND rejection_reason IS NOT NULL)
  OR (status='ACTIVATED' AND active_email IS NOT NULL AND user_id IS NOT NULL AND approved_role IS NOT NULL AND reviewed_at IS NOT NULL AND reviewed_by IS NOT NULL AND activation_hash IS NULL AND activated_at IS NOT NULL AND activation_expires_at IS NOT NULL AND rejection_reason IS NULL)
 )
);
CREATE INDEX registration_status_created ON registration_requests(status,submitted_at);
CREATE INDEX registration_personal_email ON registration_requests(personal_email);
CREATE TABLE registration_limits (
 id VARCHAR(64) PRIMARY KEY,
 window_start TIMESTAMP WITH TIME ZONE NOT NULL,
 attempts INTEGER NOT NULL CHECK(attempts>0)
);
